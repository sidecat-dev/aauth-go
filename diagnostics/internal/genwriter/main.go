// genwriter emits the combinations needed to preserve standard optional
// http.ResponseWriter interfaces without claiming unsupported capabilities.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"
)

func main() {
	types := []string{"http.Flusher", "http.Hijacker", "http.Pusher", "http.CloseNotifier", "io.ReaderFrom"}
	var out bytes.Buffer
	out.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage diagnostics\n\nimport (\"io\";\"net/http\")\n\nfunc wrapWriter(original http.ResponseWriter, observer *observerWriter) http.ResponseWriter {\nmask := 0\n")
	for i, typ := range types {
		fmt.Fprintf(&out, "v%d, ok := original.(%s); if ok { mask |= %d }\n", i, typ, 1<<i)
	}
	out.WriteString("switch mask {\ncase 0: return observer\n")
	for mask := 1; mask < 1<<len(types); mask++ {
		members := []string{"*observerWriter"}
		values := []string{"observer"}
		for i, typ := range types {
			if mask&(1<<i) != 0 {
				members = append(members, typ)
				values = append(values, fmt.Sprintf("v%d", i))
			}
		}
		fmt.Fprintf(&out, "case %d: return struct { %s }{%s}\n", mask, strings.Join(members, ";"), strings.Join(values, ","))
	}
	out.WriteString("}\npanic(\"diagnostics: invalid writer capability mask\")\n}\n")
	source, err := format.Source(out.Bytes())
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile("writer_generated.go", source, 0644); err != nil {
		panic(err)
	}
}
